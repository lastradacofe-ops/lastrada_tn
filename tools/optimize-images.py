"""Phone-first image pipeline for the LASTRADA menu.

The menu list renders a 92px thumbnail, but the source assets range from 5 KB to
313 KB at up to 1000px square. On a phone that is wasted bandwidth and decode
time. This emits small WebP derivatives and responsive hero variants; the
originals are left untouched so nothing that references them breaks.
"""
import json
import os
from PIL import Image

PUB = os.path.join('client', 'public')
MENU = os.path.join(PUB, 'assets', 'menu')

# Product thumbnails render at 92 CSS px; 288 covers a 3x phone screen.
THUMB_WIDTHS = (288, 640)
HERO_SIZES = (480, 768, 1080, 1440, 1920)
HERO_QUALITY = 78
THUMB_QUALITY = 72


def save_webp(image: Image.Image, path: str, quality: int) -> int:
    image.save(path, 'WEBP', quality=quality, method=6)
    return os.path.getsize(path)


def main() -> None:
    before = after = 0
    made = 0
    unreadable: list[str] = []
    manifest: dict[str, list[int]] = {}

    for name in sorted(os.listdir(MENU)):
        src = os.path.join(MENU, name)
        if not os.path.isfile(src) or not name.lower().endswith(('.jpg', '.jpeg', '.png')):
            continue
        base = os.path.splitext(name)[0]
        original_size = os.path.getsize(src)
        before += original_size
        smallest = original_size
        widths: list[int] = []

        try:
            im = Image.open(src)
            im.load()
        except Exception:
            # A file that is not decodable will also fail to render on the menu.
            unreadable.append(name)
            after += original_size
            continue

        with im:
            im = im.convert('RGB')
            # Only emit widths the source can actually fill — never upscale.
            usable = [w for w in THUMB_WIDTHS if w < im.width]
            if not usable:
                # Smaller than the smallest target: the original already is the thumb.
                usable = [im.width]
            for width in usable:
                out_w = min(width, im.width)
                out_h = max(1, round(im.height * out_w / im.width))
                resized = im if out_w == im.width else im.resize((out_w, out_h), Image.LANCZOS)
                size = save_webp(resized, os.path.join(MENU, f'{base}-{width}.webp'), THUMB_QUALITY)
                smallest = min(smallest, size)
                widths.append(width)

        manifest[name] = sorted(widths)
        # Footprint of the smallest derivative a phone would actually pick.
        after += smallest
        made += 1

    # The client reads this to build srcset without ever guessing a missing width.
    # Emitted as a module rather than JSON so the import typechecks and stays
    # synchronous — no fetch, no layout shift on first paint.
    module_path = os.path.join(
        'client', 'src', 'components', 'menu', 'menu-assets.generated.ts'
    )
    os.makedirs(os.path.dirname(module_path), exist_ok=True)
    lines = [
        '// GENERATED by tools/optimize-images.py - do not edit by hand.',
        '// Maps a menu asset filename to the WebP widths that were actually produced,',
        '// so srcset never references a derivative that does not exist.',
        'export const MENU_IMAGE_WIDTHS: Record<string, number[]> = {',
    ]
    for file_name in sorted(manifest):
        widths = ', '.join(str(w) for w in manifest[file_name])
        lines.append(f"  {json.dumps(file_name)}: [{widths}],")
    lines.append('};')
    with open(module_path, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')

    hero_src = os.path.join(PUB, 'lastrada-interior.jpg')
    hero_before = os.path.getsize(hero_src)
    hero_after = 0
    with Image.open(hero_src) as im:
        im = im.convert('RGB')
        for width in HERO_SIZES:
            if width > im.width * 1.15:
                continue
            out_w = min(width, im.width)
            out_h = max(1, round(im.height * out_w / im.width))
            resized = im if out_w == im.width else im.resize((out_w, out_h), Image.LANCZOS)
            size = save_webp(resized, os.path.join(PUB, f'lastrada-interior-{width}.webp'), HERO_QUALITY)
            if width == 480:
                hero_after = size

    print(f'menu assets processed : {made}')
    print(f'menu list, worst case  : {before/1024/1024:.1f} MB  ->  {after/1024/1024:.2f} MB '
          f'({after/before*100:.1f}%)')
    print(f'hero (phone, 480w)    : {hero_before/1024:.0f} KB  ->  {hero_after/1024:.0f} KB '
          f'({hero_after/hero_before*100:.0f}%)')
    if unreadable:
        print(f'\nUNREADABLE (will not render on the menu): {len(unreadable)}')
        for name in unreadable:
            print(f'  - {name}')


if __name__ == '__main__':
    main()
