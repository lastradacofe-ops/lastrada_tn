import { MENU_IMAGE_WIDTHS } from './menu-assets.generated';

const MENU_ASSET_PREFIX = '/assets/menu/';

/**
 * Builds the responsive attributes for a menu photo so phones download the
 * smallest derivative that still looks sharp.
 *
 * The list renders a 92px thumbnail, so a phone at 3x needs ~288px — not the
 * 1000px original some uploads ship. `sizes` lets the browser pick. Only
 * `/assets/menu/…` paths have derivatives; admin-uploaded data URLs keep the
 * plain `src` they were stored with.
 */
export function menuImage(src: string | undefined, sizes: string) {
  if (!src || !src.startsWith(MENU_ASSET_PREFIX)) return src ? { src } : null;

  const file = src.slice(MENU_ASSET_PREFIX.length);
  const widths = MENU_IMAGE_WIDTHS[file];
  if (!widths?.length) return { src };

  const stem = `${MENU_ASSET_PREFIX}${file.replace(/\.(jpe?g|png)$/i, '')}`;
  return {
    src,
    srcSet: widths.map(width => `${stem}-${width}.webp ${width}w`).join(', '),
    sizes,
  };
}

/** The list thumbnail: 92 CSS px, so a 3x phone needs 288 and a desktop 184. */
export const THUMB_SIZES = '(max-width: 700px) 92px, 92px';

/** The product sheet, which is a full-bleed panel on a phone. */
export const SHEET_SIZES = '(max-width: 700px) 92vw, 640px';

/** Hero variants generated by tools/optimize-images.py. */
const HERO_WIDTHS = [480, 768, 1080, 1440, 1920];
const withBase = (path: string) => `${import.meta.env.BASE_URL}${path}`.replace(/\/{2,}/g, '/');

export const heroPicture = {
  src: withBase('lastrada-interior.jpg'),
  srcSet: HERO_WIDTHS.map(width => `${withBase(`lastrada-interior-${width}.webp`)} ${width}w`).join(', '),
  // Phone-first: a narrow viewport is served roughly viewport width; only from
  // 1024px up does the hero take a fixed slice of a 1120px stage.
  sizes: '(max-width: 1023px) 100vw, 670px',
};
